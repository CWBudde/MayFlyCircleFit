// ARM64 NEON opaque-span compositor.
//
// Eight interleaved NRGBA pixels are deinterleaved per iteration. Each color
// channel is widened to four pairs of float64 lanes, composited with the same
// fused multiply-add sequence emitted for the scalar Go expression, narrowed,
// and stored with the original opaque alpha bytes.

#include "textflag.h"

DATA ·compositeInv255<>+0(SB)/8, $0x3f70101010101010
GLOBL ·compositeInv255<>(SB), RODATA|NOPTR, $8
DATA ·composite255<>+0(SB)/8, $0x406fe00000000000
GLOBL ·composite255<>(SB), RODATA|NOPTR, $8
DATA ·compositeHalf<>+0(SB)/8, $0x3fe0000000000000
GLOBL ·compositeHalf<>(SB), RODATA|NOPTR, $8

// func compositeOpaqueSpanNEON(pix unsafe.Pointer, pixels int,
//     fgR, fgG, fgB, bgBlend float64)
TEXT ·compositeOpaqueSpanNEON(SB), NOSPLIT, $0-48
	MOVD	pix+0(FP), R0
	MOVD	pixels+8(FP), R1

	FMOVD	fgR+16(FP), F26
	VDUP	V26.D[0], V26.D2
	FMOVD	fgG+24(FP), F27
	VDUP	V27.D[0], V27.D2
	FMOVD	fgB+32(FP), F28
	VDUP	V28.D[0], V28.D2
	FMOVD	bgBlend+40(FP), F25
	VDUP	V25.D[0], V25.D2

	MOVD	$·compositeInv255<>(SB), R2
	VLD1R	(R2), [V24.D2]
	MOVD	$·composite255<>(SB), R2
	VLD1R	(R2), [V29.D2]
	MOVD	$·compositeHalf<>(SB), R2
	VLD1R	(R2), [V30.D2]

loop:
	VLD4	(R0), [V0.B8, V1.B8, V2.B8, V3.B8]

	// Widen red bytes into four uint64 vectors.
	VUXTL	V0.B8, V16.H8
	VUXTL	V16.H4, V17.S4
	VUXTL2	V16.H8, V18.S4
	VUXTL	V17.S2, V4.D2
	VUXTL2	V17.S4, V5.D2
	VUXTL	V18.S2, V6.D2
	VUXTL2	V18.S4, V7.D2

	// Widen green bytes.
	VUXTL	V1.B8, V16.H8
	VUXTL	V16.H4, V17.S4
	VUXTL2	V16.H8, V18.S4
	VUXTL	V17.S2, V8.D2
	VUXTL2	V17.S4, V9.D2
	VUXTL	V18.S2, V10.D2
	VUXTL2	V18.S4, V11.D2

	// Widen blue bytes.
	VUXTL	V2.B8, V16.H8
	VUXTL	V16.H4, V17.S4
	VUXTL2	V16.H8, V18.S4
	VUXTL	V17.S2, V12.D2
	VUXTL2	V17.S4, V13.D2
	VUXTL	V18.S2, V14.D2
	VUXTL2	V18.S4, V15.D2

	// UCVTF V4.2D..V15.2D. Go's assembler does not expose the
	// Advanced SIMD integer-to-float conversion mnemonic.
	WORD	$0x6e61d884
	WORD	$0x6e61d8a5
	WORD	$0x6e61d8c6
	WORD	$0x6e61d8e7
	WORD	$0x6e61d908
	WORD	$0x6e61d929
	WORD	$0x6e61d94a
	WORD	$0x6e61d96b
	WORD	$0x6e61d98c
	WORD	$0x6e61d9ad
	WORD	$0x6e61d9ce
	WORD	$0x6e61d9ef

	// Scale byte values by 1/255. V16 is reset before every FMLA so
	// the fused operation is exactly a multiply with a zero addend.
	VEOR	V16.B16, V16.B16, V16.B16
	VFMLA	V4.D2, V24.D2, V16.D2
	VEOR	V17.B16, V17.B16, V17.B16
	VFMLA	V5.D2, V24.D2, V17.D2
	VEOR	V18.B16, V18.B16, V18.B16
	VFMLA	V6.D2, V24.D2, V18.D2
	VEOR	V19.B16, V19.B16, V19.B16
	VFMLA	V7.D2, V24.D2, V19.D2
	VMOV	V16.B16, V4.B16
	VMOV	V17.B16, V5.B16
	VMOV	V18.B16, V6.B16
	VMOV	V19.B16, V7.B16

	VEOR	V16.B16, V16.B16, V16.B16
	VFMLA	V8.D2, V24.D2, V16.D2
	VEOR	V17.B16, V17.B16, V17.B16
	VFMLA	V9.D2, V24.D2, V17.D2
	VEOR	V18.B16, V18.B16, V18.B16
	VFMLA	V10.D2, V24.D2, V18.D2
	VEOR	V19.B16, V19.B16, V19.B16
	VFMLA	V11.D2, V24.D2, V19.D2
	VMOV	V16.B16, V8.B16
	VMOV	V17.B16, V9.B16
	VMOV	V18.B16, V10.B16
	VMOV	V19.B16, V11.B16

	VEOR	V16.B16, V16.B16, V16.B16
	VFMLA	V12.D2, V24.D2, V16.D2
	VEOR	V17.B16, V17.B16, V17.B16
	VFMLA	V13.D2, V24.D2, V17.D2
	VEOR	V18.B16, V18.B16, V18.B16
	VFMLA	V14.D2, V24.D2, V18.D2
	VEOR	V19.B16, V19.B16, V19.B16
	VFMLA	V15.D2, V24.D2, V19.D2
	VMOV	V16.B16, V12.B16
	VMOV	V17.B16, V13.B16
	VMOV	V18.B16, V14.B16
	VMOV	V19.B16, V15.B16

	// Source-over on opaque destinations: fg + normalized-bg*blend.
	VMOV	V26.B16, V20.B16
	VFMLA	V4.D2, V25.D2, V20.D2
	VMOV	V26.B16, V21.B16
	VFMLA	V5.D2, V25.D2, V21.D2
	VMOV	V26.B16, V22.B16
	VFMLA	V6.D2, V25.D2, V22.D2
	VMOV	V26.B16, V23.B16
	VFMLA	V7.D2, V25.D2, V23.D2
	VMOV	V20.B16, V4.B16
	VMOV	V21.B16, V5.B16
	VMOV	V22.B16, V6.B16
	VMOV	V23.B16, V7.B16

	VMOV	V27.B16, V20.B16
	VFMLA	V8.D2, V25.D2, V20.D2
	VMOV	V27.B16, V21.B16
	VFMLA	V9.D2, V25.D2, V21.D2
	VMOV	V27.B16, V22.B16
	VFMLA	V10.D2, V25.D2, V22.D2
	VMOV	V27.B16, V23.B16
	VFMLA	V11.D2, V25.D2, V23.D2
	VMOV	V20.B16, V8.B16
	VMOV	V21.B16, V9.B16
	VMOV	V22.B16, V10.B16
	VMOV	V23.B16, V11.B16

	VMOV	V28.B16, V20.B16
	VFMLA	V12.D2, V25.D2, V20.D2
	VMOV	V28.B16, V21.B16
	VFMLA	V13.D2, V25.D2, V21.D2
	VMOV	V28.B16, V22.B16
	VFMLA	V14.D2, V25.D2, V22.D2
	VMOV	V28.B16, V23.B16
	VFMLA	V15.D2, V25.D2, V23.D2
	VMOV	V20.B16, V12.B16
	VMOV	V21.B16, V13.B16
	VMOV	V22.B16, V14.B16
	VMOV	V23.B16, V15.B16

	// Round, convert, and narrow one channel at a time. V20-V23 are
	// scratch accumulators for the fused out*255 + 0.5 operation.
	VMOV	V30.B16, V20.B16
	VFMLA	V4.D2, V29.D2, V20.D2
	VMOV	V30.B16, V21.B16
	VFMLA	V5.D2, V29.D2, V21.D2
	VMOV	V30.B16, V22.B16
	VFMLA	V6.D2, V29.D2, V22.D2
	VMOV	V30.B16, V23.B16
	VFMLA	V7.D2, V29.D2, V23.D2
	WORD	$0x6ee1ba94 // FCVTZU V20.2D, V20.2D
	WORD	$0x6ee1bab5 // FCVTZU V21.2D, V21.2D
	WORD	$0x6ee1bad6 // FCVTZU V22.2D, V22.2D
	WORD	$0x6ee1baf7 // FCVTZU V23.2D, V23.2D
	WORD	$0x0ea12a90 // XTN V20.2D, V16.2S
	WORD	$0x4ea12ab0 // XTN2 V21.2D, V16.4S
	WORD	$0x0ea12ad1 // XTN V22.2D, V17.2S
	WORD	$0x4ea12af1 // XTN2 V23.2D, V17.4S
	WORD	$0x0e612a12 // XTN V16.4S, V18.4H
	WORD	$0x4e612a32 // XTN2 V17.4S, V18.8H
	WORD	$0x0e212a40 // XTN V18.8H, V0.8B

	VMOV	V30.B16, V20.B16
	VFMLA	V8.D2, V29.D2, V20.D2
	VMOV	V30.B16, V21.B16
	VFMLA	V9.D2, V29.D2, V21.D2
	VMOV	V30.B16, V22.B16
	VFMLA	V10.D2, V29.D2, V22.D2
	VMOV	V30.B16, V23.B16
	VFMLA	V11.D2, V29.D2, V23.D2
	WORD	$0x6ee1ba94
	WORD	$0x6ee1bab5
	WORD	$0x6ee1bad6
	WORD	$0x6ee1baf7
	WORD	$0x0ea12a90
	WORD	$0x4ea12ab0
	WORD	$0x0ea12ad1
	WORD	$0x4ea12af1
	WORD	$0x0e612a12
	WORD	$0x4e612a32
	WORD	$0x0e212a41 // XTN V18.8H, V1.8B

	VMOV	V30.B16, V20.B16
	VFMLA	V12.D2, V29.D2, V20.D2
	VMOV	V30.B16, V21.B16
	VFMLA	V13.D2, V29.D2, V21.D2
	VMOV	V30.B16, V22.B16
	VFMLA	V14.D2, V29.D2, V22.D2
	VMOV	V30.B16, V23.B16
	VFMLA	V15.D2, V29.D2, V23.D2
	WORD	$0x6ee1ba94
	WORD	$0x6ee1bab5
	WORD	$0x6ee1bad6
	WORD	$0x6ee1baf7
	WORD	$0x0ea12a90
	WORD	$0x4ea12ab0
	WORD	$0x0ea12ad1
	WORD	$0x4ea12af1
	WORD	$0x0e612a12
	WORD	$0x4e612a32
	WORD	$0x0e212a42 // XTN V18.8H, V2.8B

	VST4.P	[V0.B8, V1.B8, V2.B8, V3.B8], 32(R0)
	SUB	$8, R1, R1
	CBNZ	R1, loop
	RET
