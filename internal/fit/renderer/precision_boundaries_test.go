const (
	// precisionQ16 is one Q16.16 unit expressed in float64: the step of the
	// renderer's fixed-point geometry. It is a power of two, so every offset
	// built from it below is exact in binary64.
	precisionQ16 = 1.0 / 65536.0
	// precisionQ16Half is half a Q16.16 unit. Adding it to an integer puts
	// floatToQ16's math.Round argument exactly on a .5 tie, which is the
	// rounding boundary the fractional cases exist to pin.
	precisionQ16Half = precisionQ16 / 2
)

// precisionCanvasKind selects the base canvas a scene renders onto. It is an
// axis of the matrix rather than a detail: an opaque canvas takes the SIMD span
// compositors and a translucent one takes the per-pixel Porter-Duff path, so a
// boundary case measured only on white measures only half the renderer.
type precisionCanvasKind int

const (
	precisionCanvasWhite precisionCanvasKind = iota
	precisionCanvasOpaque
	precisionCanvasTranslucent
)

// precisionScene is one case of the matrix.
type precisionScene struct {
	name          string
	width, height int
	canvas        precisionCanvasKind
	circles       []fit.Circle
}

// precisionRNG is SplitMix64. The generator is local, and its output is defined
// entirely by uint64 arithmetic, so the reference images and the randomized
// circle draws are identical on every architecture and cannot drift with a
// change to math/rand.
type precisionRNG struct {
	state uint64
}

func newPrecisionRNG(seed uint64) *precisionRNG {
	return &precisionRNG{state: seed}
}

func (r *precisionRNG) next() uint64 {
	r.state += 0x9e3779b97f4a7c15
	mixed := r.state
	mixed = (mixed ^ (mixed >> 30)) * 0xbf58476d1ce4e5b9
	mixed = (mixed ^ (mixed >> 27)) * 0x94d049bb133111eb

	return mixed ^ (mixed >> 31)
}

// unitFloat returns a value in [0,1) built from 53 mantissa bits.
func (r *precisionRNG) unitFloat() float64 {
	return float64(r.next()>>11) / float64(uint64(1)<<53)
}

func (r *precisionRNG) nextByte() uint8 {
	return uint8(r.next() >> 56)
}

// precisionImage builds a deterministic NRGBA image. Opaque images pin alpha at
// 255 so the renderer selects its span compositors; translucent ones vary it so
// the general per-pixel path is exercised instead.
func precisionImage(width, height int, seed uint64, opaque bool) *image.NRGBA {
	rng := newPrecisionRNG(seed)
	img := image.NewNRGBA(image.Rect(0, 0, width, height))

	for i := 0; i < len(img.Pix); i += 4 {
		img.Pix[i+0] = rng.nextByte()
		img.Pix[i+1] = rng.nextByte()
		img.Pix[i+2] = rng.nextByte()

		if opaque {
			img.Pix[i+3] = 255
			continue
		}

		// Keep a spread of alphas including both extremes.
		img.Pix[i+3] = rng.nextByte()
	}

	return img
}

func precisionReference(width, height int) *image.NRGBA {
	return precisionImage(width, height, 0x5150_1020_0001, true)
}

func (s precisionScene) baseCanvas() *image.NRGBA {
	switch s.canvas {
	case precisionCanvasWhite:
		return nil
	case precisionCanvasOpaque:
		return precisionImage(s.width, s.height, 0x5150_1020_0002, true)
	case precisionCanvasTranslucent:
		return precisionImage(s.width, s.height, 0x5150_1020_0003, false)
	default:
		return nil
	}
}

// precisionRender renders one scene at the given shard count and returns an
// independent copy of the pixels together with the exact cost. The buffer is
// copied because CPURenderer reuses it.
func precisionRender(scene precisionScene, threads int) ([]byte, float64) {
	reference := precisionReference(scene.width, scene.height)
	params := encodeCircles(scene.circles)

	var renderer *CPURenderer
	if base := scene.baseCanvas(); base != nil {
		renderer = NewCPURendererWithCanvas(reference, base, len(scene.circles))
	} else {
		renderer = NewCPURenderer(reference, len(scene.circles))
	}

	renderer.SetThreads(threads)

	rendered := renderer.Render(params)
	pixels := append([]byte(nil), rendered.Pix...)

	return pixels, renderer.Cost(params)
}

// precisionDigest folds the rendered bytes and the exact cost into one hash.
// The cost is included deliberately: it routes through the SSD kernels, so the
// digest covers the tier-dispatched cost path as well as the compositors.
func precisionDigest(pixels []byte, cost float64) string {
	sum := sha256.New()
	_, _ = sum.Write(pixels)

	var costBits [8]byte

	binary.BigEndian.PutUint64(costBits[:], math.Float64bits(cost))
	_, _ = sum.Write(costBits[:])

	return hex.EncodeToString(sum.Sum(nil))
}

// precisionShardCounts returns shard counts that are valid at any core count.
// Nothing here may name a fixed worker count: SetThreads caps at GOMAXPROCS and
// at the image height, and the macOS ARM64 CI runner has three processors, so a
// test asserting on four workers fails there and nowhere else.
func precisionShardCounts(height int) []int {
	candidates := []int{1, 2, 3, runtime.GOMAXPROCS(0), height}

	counts := make([]int, 0, len(candidates))
	seen := make(map[int]bool, len(candidates))

	for _, candidate := range candidates {
		effective := effectiveThreadCount(candidate, height)
		if seen[effective] {
			continue
		}

		seen[effective] = true

		counts = append(counts, effective)
	}

	return counts
}

// assertPixelsEqual reports the first differing pixel rather than the buffers,
// so a cross-tier or cross-shard failure names a coordinate and a channel.
func assertPixelsEqual(t *testing.T, got, want []byte, width int, context string) {
	t.Helper()

	if len(got) != len(want) {
		t.Fatalf("%s: pixel buffer length = %d, want %d", context, len(got), len(want))
	}

	for i := range want {
		if got[i] == want[i] {
			continue
		}

		pixel := i / 4
		t.Fatalf("%s: pixel (%d,%d) channel %d = %d, want %d", context, pixel%width, pixel/width, i%4, got[i], want[i])
	}
}

