// TestRendererPrecisionRowSharding asserts both halves of the contract on one
// twelve-circle scene.
//
// Within the process it pins the property the row walk is built on: workers own
// disjoint bands, so the number of bands cannot change a pixel. Across
// processes, the single-threaded render that serves as this sweep's oracle is
// itself pinned to a recorded digest, exactly as every named scene is. Without
// that anchor the sweep would only prove internal consistency, and a scene that
// rendered differently on ARM64 while staying shard-invariant there would still
// pass on both architectures.
//
// GOMAXPROCS is raised for the duration because SetThreads caps at it, and a
// three-processor runner would otherwise reduce every shard count in the sweep
// to three. Sharding correctness does not depend on the bands actually running
// in parallel, so this measures the same property on any host.
//
//nolint:paralleltest // forces the process-global SIMD tier, which no two tests may do at once
func TestRendererPrecisionRowSharding(t *testing.T) {
	const (
		width  = 71
		height = 53
	)

	previous := runtime.GOMAXPROCS(max(runtime.GOMAXPROCS(0), height))

	t.Cleanup(func() { runtime.GOMAXPROCS(previous) })
	t.Cleanup(fit.ResetTierDetection)

	scene := precisionScene{
		name: "sharding", width: width, height: height, canvas: precisionCanvasOpaque,
		circles: precisionRandomScene(newPrecisionRNG(0x5150_1020_5ABD), width, height, 12),
	}

	want, wantCost := precisionRender(scene, 1)

	// The cross-architecture anchor, asserted before this buffer is used as the
	// oracle below.
	recorded, ok := precisionDigests[scene.name]
	if !ok {
		t.Fatalf("scene has no recorded digest; measured %q", precisionDigest(want, wantCost))
	}

	if got := precisionDigest(want, wantCost); got != recorded {
		t.Errorf("digest = %q, recorded %q (cost %v)", got, recorded, wantCost)
	}

	// Every band count from one to one row per worker, plus the values that
	// exercise a band boundary landing on a circle's extreme row.
	shardCounts := []int{1, 2, 3, 5, 7, 8, 11, 16, 17, 32, height - 1, height, height + 1}

	tiers := fit.SupportedTiers()

	//nolint:paralleltest // each subtest renders under a forced tier the loop owns
	for _, tier := range tiers {
		if testing.Short() && tier != fit.Tier() {
			continue
		}

		fit.SetForcedTier(tier)

		for _, threads := range shardCounts {
			t.Run(fmt.Sprintf("%s/shards_%d", tier, threads), func(t *testing.T) {
				got, cost := precisionRender(scene, threads)
				assertPixelsEqual(t, got, want, width, fmt.Sprintf("tier %s, %d shards", tier, threads))

				if cost != wantCost {
					t.Errorf("tier %s, %d shards: cost = %v, want %v", tier, threads, cost, wantCost)
				}
			})
		}

		fit.ResetTierDetection()
	}
}

// TestRendererPrecisionBatchPipelineBoundaries covers the batch pipeline's own
// boundaries rather than the span search's. Two properties are asserted:
//
//   - The accumulated audit stepper keeps a composited prefix instead of
//     replaying the draw order, and planAudit hands runs of that order to
//     several sessions at once. Neither may move a byte or a cost, so the
//     parallel audit must equal the serial one exactly.
//   - compositeParams draws onto a caller-owned canvas without resetting it,
//     which is what lets a retained prefix be reused. The result must equal a
//     full render of the same vector.
//
// The circle count is chosen to cross minAuditChunkCircles*auditChunksPerWorker,
// below which planAudit deliberately stays serial.
//
//nolint:paralleltest // forces the process-global SIMD tier, which no two tests may do at once
func TestRendererPrecisionBatchPipelineBoundaries(t *testing.T) {
	const (
		width   = 64
		height  = 40
		circles = minAuditChunkCircles * auditChunksPerWorker * 2
	)

	reference := precisionReference(width, height)
	base := precisionImage(width, height, 0x5150_1020_0002, true)
	drawn := precisionRandomScene(newPrecisionRNG(0x5150_1020_BA7C), width, height, circles)
	params := encodeCircles(drawn)

	serial := NewCPURendererWithCanvas(reference, base, circles)
	serial.SetThreads(1)

	serialAudit, err := AuditCircleBatch(serial, params)
	if err != nil {
		t.Fatalf("serial AuditCircleBatch: %v", err)
	}

	parallel := NewCPURendererWithCanvas(reference, base, circles)
	parallel.SetThreads(max(2, runtime.GOMAXPROCS(0)))

	parallelAudit, err := AuditCircleBatch(parallel, params)
	if err != nil {
		t.Fatalf("parallel AuditCircleBatch: %v", err)
	}

	if parallelAudit.MSE != serialAudit.MSE {
		t.Errorf("parallel audit MSE = %v, serial = %v", parallelAudit.MSE, serialAudit.MSE)
	}

	if len(parallelAudit.Circles) != len(serialAudit.Circles) {
		t.Fatalf("parallel audit reported %d circles, serial %d", len(parallelAudit.Circles), len(serialAudit.Circles))
	}

	for i := range serialAudit.Circles {
		if parallelAudit.Circles[i] != serialAudit.Circles[i] {
			t.Errorf("circle %d: parallel audit = %+v, serial = %+v", i+1, parallelAudit.Circles[i], serialAudit.Circles[i])
		}
	}

	// An incrementally composited prefix plus its suffix must equal a full
	// render of the whole vector, at every split point around the chunk size.
	full := append([]byte(nil), serial.Render(params).Pix...)

	//nolint:paralleltest // the subtests share one renderer and its reusable canvas
	for _, prefix := range []int{0, 1, minAuditChunkCircles, minAuditChunkCircles * auditChunksPerWorker, circles} {
		t.Run(fmt.Sprintf("prefix_%d", prefix), func(t *testing.T) {
			canvas := serial.initialCanvas()
			serial.compositeParams(canvas, params, prefix)
			serial.compositeParams(canvas, params[prefix*paramsPerCircle:], circles-prefix)
			assertPixelsEqual(t, canvas.Pix, full, width, fmt.Sprintf("prefix %d", prefix))
		})
	}
}

// TestSpanSearchAlwaysCoversNearestSample records a rasterization rule that the
// correctness matrix did not previously reach, and that
// docs/renderer-precision-measurements.md analyses in full.
//
// circleSpanFloat64 and fixedCircleQ16.span both start at int(centerX+0.5) and
// walk outward, so that pixel is painted on every row the disc touches -- even
// on a tangent row where its distance to the center exceeds the radius. On such
// a row the historical bounding-box rasterizer paints nothing, so the two
// disagree by one pixel. It is a property of the center-out search, not of the
// number format: the float64 and the Q16.16 paths do it identically, and so
// does every architecture and tier.
//
// The rule is pinned rather than changed. Changing it would move rendered
// output, and therefore every recorded cost in docs/, for about one row in
// twelve thousand.
//
//nolint:paralleltest // shares the process-global SIMD tier the tests above force
func TestSpanSearchAlwaysCoversNearestSample(t *testing.T) {
	tests := []struct {
		name      string
		centerX   float64
		remaining float64
		width     int
		want      [2]int
	}{
		{name: "tangent_row_half_pixel_center", centerX: 10.5, remaining: 0, width: 21, want: [2]int{11, 12}},
		{name: "tangent_row_integer_center", centerX: 10, remaining: 0, width: 21, want: [2]int{10, 11}},
		{name: "row_narrower_than_half_pixel", centerX: 10.5, remaining: 0.2, width: 21, want: [2]int{11, 12}},
		{name: "row_reaching_both_samples", centerX: 10.5, remaining: 0.25, width: 21, want: [2]int{10, 12}},
	}

	//nolint:paralleltest // shares the process-global SIMD tier the tests above force
	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			start, end := circleSpanFloat64(test.centerX, test.remaining, test.width)
			if [2]int{start, end} != test.want {
				t.Errorf("circleSpanFloat64 = [%d,%d), want [%d,%d)", start, end, test.want[0], test.want[1])
			}

			one, two := circleSpanFloat64OnePixel(test.centerX, test.remaining, test.width)
			if [2]int{one, two} != test.want {
				t.Errorf("circleSpanFloat64OnePixel = [%d,%d), want [%d,%d)", one, two, test.want[0], test.want[1])
			}
		})
	}

	// The same rule holds through the production Q16.16 path: a disc whose
	// extreme row reaches no integer sample still paints one pixel there.
	geometry, ok := newFixedCircleQ16(fit.Circle{X: 10.5, Y: 10, R: 1})
	if !ok {
		t.Fatal("newFixedCircleQ16 refused an ordinary circle")
	}

	start, end, intersects := geometry.span(11, 21)
	if !intersects || start != 11 || end != 12 {
		t.Errorf("fixedCircleQ16.span(11) = [%d,%d) intersects=%v, want [11,12) true", start, end, intersects)
	}
}

// TestSpanSearchOverCoverageRate bounds how often the rule above actually
// fires. It is the quantified half of TestSpanSearchAlwaysCoversNearestSample:
// the deviation is real, so the thing worth guarding is its size.
//
// The comparison is against the exact integer interval, computed with
// math.Sqrt rather than by walking, so the oracle shares no code with the
// search. Under-coverage would be a defect of a different kind -- the search
// missing a pixel that is inside the disc -- and is asserted to be impossible.
//
//nolint:paralleltest // shares the process-global SIMD tier the tests above force
func TestSpanSearchOverCoverageRate(t *testing.T) {
	if testing.Short() {
		t.Skip("sweeps 200,000 circles")
	}

	const (
		width   = 513
		height  = 389
		circles = 200_000
		seed    = 0x5150_1020_C0FE
	)

	rng := newPrecisionRNG(seed)
	rows, overCovered, underCovered := 0, 0, 0

	for range circles {
		centerX := rng.unitFloat() * width
		centerY := rng.unitFloat() * height
		radius := fit.MinCircleRadius + rng.unitFloat()*64
		radiusSquared := radius * radius

		for y := range height {
			dy := float64(y) - centerY

			remaining := radiusSquared - dy*dy
			if remaining < 0 {
				continue
			}

			rows++

			start, end := circleSpanFloat64(centerX, remaining, width)
			start = max(start, 0)
			end = min(end, width)

			root := math.Sqrt(remaining)
			wantStart := max(int(math.Ceil(centerX-root)), 0)
			wantEnd := min(int(math.Floor(centerX+root)), width-1) + 1

			painted := end > start
			covered := wantEnd > wantStart

			switch {
			case !covered:
				// No integer sample on this row lies inside the disc.
				if painted {
					overCovered++
				}
			case !painted:
				underCovered++
			case start == wantStart && end == wantEnd:
			case start <= wantStart && end >= wantEnd:
				overCovered++
			default:
				underCovered++
			}
		}
	}

	if underCovered != 0 {
		t.Errorf("span search under-covered %d of %d intersecting rows; want 0", underCovered, rows)
	}

	// Measured at 1,110 of 12,466,238 rows (0.0089%) on both amd64 and arm64.
	// The bound is an order of magnitude above that, so it catches a change of
	// kind rather than a change of a few rows.
	if overCovered > rows/10_000 {
		t.Errorf("span search over-covered %d of %d intersecting rows; want at most 0.01%%", overCovered, rows)
	}

	t.Logf("span search over-covered %d of %d intersecting rows (%.4f%%), under-covered %d",
		overCovered, rows, 100*float64(overCovered)/float64(rows), underCovered)
}
