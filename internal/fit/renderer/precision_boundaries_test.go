// precisionScenes is the named half of the matrix. Every case the plan item
// lists appears here except the randomized draws and the row-shard sweep, which
// have their own tests below.
func precisionScenes() []precisionScene {
	scenes := make([]precisionScene, 0, 32)
	scenes = append(scenes, precisionFractionalScenes()...)
	scenes = append(scenes, precisionTangentScenes()...)
	scenes = append(scenes, precisionRadiusScenes()...)
	scenes = append(scenes, precisionClippingScenes()...)
	scenes = append(scenes, precisionBatchScenes()...)

	return scenes
}

