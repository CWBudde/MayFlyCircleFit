func TestBundleIsEmbeddedAndGenerated(t *testing.T) {
	asset, ok := staticAssets[bundleName]
	if !ok {
		t.Fatalf("bundle %q is not embedded; run `just bundle`", bundleName)
	}
	if len(asset.content) == 0 {
		t.Fatal("embedded bundle is empty")
	}
	if !bytes.HasPrefix(asset.content, []byte("// Code generated by scripts/bundle-web.sh")) {
		t.Errorf("embedded bundle is missing the generated-file banner; first bytes: %q", firstLine(asset.content))
	}
	if !bytes.Contains(asset.content, []byte("data-island")) {
		t.Error("embedded bundle does not reference the data-island mount convention, so it cannot be the island entry point")
	}
}

func TestBundleURLCarriesTheContentHash(t *testing.T) {
	url := BundleURL()
	prefix := StaticPrefix + bundleName + "?v="
	if !strings.HasPrefix(url, prefix) {
		t.Fatalf("BundleURL() = %q, want prefix %q", url, prefix)
	}
	version := strings.TrimPrefix(url, prefix)
	if version != staticAssets[bundleName].version {
		t.Errorf("BundleURL() version = %q, want %q", version, staticAssets[bundleName].version)
	}
	if len(version) != 16 {
		t.Errorf("version %q is %d characters, want 16", version, len(version))
	}
}

func TestStaticHandlerServesTheBundle(t *testing.T) {
	recorder := httptest.NewRecorder()
	request := httptest.NewRequest(http.MethodGet, BundleURL(), nil)
	StaticHandler().ServeHTTP(recorder, request)

	if recorder.Code != http.StatusOK {
		t.Fatalf("status = %d, want %d", recorder.Code, http.StatusOK)
	}
	if got, want := recorder.Header().Get("Content-Type"), "text/javascript; charset=utf-8"; got != want {
		t.Errorf("Content-Type = %q, want %q", got, want)
	}
	if got, want := recorder.Header().Get("X-Content-Type-Options"), "nosniff"; got != want {
		t.Errorf("X-Content-Type-Options = %q, want %q", got, want)
	}
	// A URL that names the version it receives can never go stale, so it is
	// the only case allowed to opt out of revalidation.
	if got, want := recorder.Header().Get("Cache-Control"), "public, max-age=31536000, immutable"; got != want {
		t.Errorf("Cache-Control = %q, want %q", got, want)
	}
	if !bytes.Equal(recorder.Body.Bytes(), staticAssets[bundleName].content) {
		t.Error("served body does not match the embedded bundle")
	}
}

func TestStaticHandlerRevalidatesUnversionedAndStaleURLs(t *testing.T) {
	for name, url := range map[string]string{
		"no version":    StaticPrefix + bundleName,
		"stale version": StaticPrefix + bundleName + "?v=0000000000000000",
	} {
		t.Run(name, func(t *testing.T) {
			recorder := httptest.NewRecorder()
			StaticHandler().ServeHTTP(recorder, httptest.NewRequest(http.MethodGet, url, nil))

			if recorder.Code != http.StatusOK {
				t.Fatalf("status = %d, want %d", recorder.Code, http.StatusOK)
			}
			if got, want := recorder.Header().Get("Cache-Control"), "no-cache"; got != want {
				t.Errorf("Cache-Control = %q, want %q", got, want)
			}
		})
	}
}

func TestStaticHandlerHonorsIfNoneMatch(t *testing.T) {
	request := httptest.NewRequest(http.MethodGet, BundleURL(), nil)
	request.Header.Set("If-None-Match", staticAssets[bundleName].etag)

	recorder := httptest.NewRecorder()
	StaticHandler().ServeHTTP(recorder, request)

	if recorder.Code != http.StatusNotModified {
		t.Fatalf("status = %d, want %d", recorder.Code, http.StatusNotModified)
	}
	if recorder.Body.Len() != 0 {
		t.Errorf("304 response carried %d bytes of body", recorder.Body.Len())
	}
}

func TestStaticHandlerRejectsAnythingNotEmbedded(t *testing.T) {
	cases := map[string]struct {
		method string
		url    string
		want   int
	}{
		"unknown asset":     {http.MethodGet, StaticPrefix + "nope.js", http.StatusNotFound},
		"directory listing": {http.MethodGet, StaticPrefix, http.StatusNotFound},
		"nested path":       {http.MethodGet, StaticPrefix + "sub/dashboard.js", http.StatusNotFound},
		"traversal":         {http.MethodGet, StaticPrefix + "../go.mod", http.StatusNotFound},
		"write attempt":     {http.MethodPost, StaticPrefix + bundleName, http.StatusMethodNotAllowed},
	}
	for name, testCase := range cases {
		t.Run(name, func(t *testing.T) {
			recorder := httptest.NewRecorder()
			StaticHandler().ServeHTTP(recorder, httptest.NewRequest(testCase.method, testCase.url, nil))
			if recorder.Code != testCase.want {
				t.Errorf("status = %d, want %d", recorder.Code, testCase.want)
			}
		})
	}
}

func TestLayoutLoadsTheIslandBundle(t *testing.T) {
	var output bytes.Buffer
	if err := Layout("Bundle test").Render(context.Background(), &output); err != nil {
		t.Fatalf("render layout: %v", err)
	}

	body := output.String()
	if !strings.Contains(body, `type="module"`) {
		t.Error("layout does not load the bundle as a module script")
	}
	// The versioned URL must reach the markup: a page that links the
	// unversioned path would keep serving a stale bundle from cache after a
	// rebuild.
	if !strings.Contains(body, BundleURL()) {
		t.Errorf("layout does not reference %q", BundleURL())
	}
}

func firstLine(content []byte) []byte {
	if index := bytes.IndexByte(content, '\n'); index >= 0 {
		return content[:index]
	}
	return content
}
